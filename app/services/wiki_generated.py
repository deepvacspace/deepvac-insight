"""The wiki's generated pages, written from the data."""

import sqlite3
import statistics
import struct
from collections import defaultdict
from datetime import datetime

from app.api import control_settings


def _header(page_id, title, tags, sources, summary):
    today = datetime.now().strftime("%Y-%m-%d")
    return (
        f"---\ntitle: {title}\ntype: generated\ntags: [{', '.join(tags)}]\nsources: [{', '.join(sources)}]\n"
        f"updated: {today}\n---\n# {title}\n\n{summary}\n\n"
        f"> Generated by `scripts/build_brain.py` on {datetime.now():%Y-%m-%d %H:%M} from the data: don't edit, "
        "changes are overwritten.\n"
    )


def _g(value, digits=4):
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.{digits}g}"
    return str(value)


def _table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += [
        "| " + " | ".join(_g(c) if not isinstance(c, str) else c for c in row) + " |"
        for row in rows
    ]
    return "\n".join(lines)


def _bits_of_float(value) -> str:
    """Returns the bit mask stored as a float."""
    try:
        bits = struct.unpack("<I", struct.pack("<f", float(value)))[0]
    except (TypeError, ValueError, struct.error):
        return _g(value)
    return f"0x{bits:08X} (bits {', '.join(str(b) for b in range(32) if bits >> b & 1) or 'none'})"


def chamber_configuration(settings: dict | None = None) -> str:
    s = settings if settings is not None else control_settings.load()
    page = _header(
        "chamber-configuration",
        "Chamber configuration",
        [
            "configuration",
            "channels",
            "alarms",
            "plc settings",
            "pid table",
            "calibration",
            "outputs",
        ],
        ["insight data/control_settings.json (copied from Deepvac Control settings.json)"],
        "The chamber's current configuration: its channels, alarms, PLC settings, PID table, calibration and "
        "output bits, as Deepvac Control and Insight use them. What they mean: [[chamber-overview]], "
        "[[pid-control]], [[alarms]].",
    )
    parts = [page]
    temp = next((p for p in s.get("control_params") or [] if p.get("name") == "temp"), {})
    if temp:
        parts.append(
            f"\n## Setpoint range\n\n{_g(temp.get('min'))} … {_g(temp.get('max'))} °C "
            "(program and manual setpoints are checked against it).\n"
        )
    default = s.get("default_program") or {}
    if default:
        flags = int(default.get("flags", 0))
        mode = "ramp" if flags >> 9 & 1 else ("go to and hold" if flags >> 8 & 1 else "step")
        parts.append(
            f"\nDefault program interval: {_g(default.get('temp'))} °C, {_g(default.get('duration'))} s, "
            f"{mode} (flags {flags}).\n"
        )

    meta = control_settings.state_meta(s)
    parts.append(
        "\n## Channels\n\nWhat the PLC sends, about once a second, in this order.\n\n"
        + _table(
            ["Channel", "Meaning", "Unit"],
            [
                [
                    f"`{st['name']}`",
                    meta.get(st["name"], {}).get("label", ""),
                    meta.get(st["name"], {}).get("unit", ""),
                ]
                for st in s.get("states") or []
            ],
        )
    )
    alarms = s.get("alarms") or []
    if alarms:
        parts.append(
            "\n\n## Alarms\n\nBits of `alarm_out_status`.\n\n"
            + _table(["Bit", "Alarm"], [[str(a.get("index")), a.get("label", "")] for a in alarms])
        )
    general = (s.get("plc_settings") or {}).get("general") or []
    if general:
        rows = []
        for g in general:
            value = (
                _bits_of_float(g.get("value"))
                if str(g.get("name", "")).startswith("alarm_cfg")
                else _g(g.get("value"))
            )
            rows.append(
                [
                    f"`{g.get('name')}`",
                    g.get("label", ""),
                    value,
                    f"{_g(g.get('min'))} … {_g(g.get('max'))}",
                ]
            )
        parts.append(
            "\n\n## PLC settings\n\n" + _table(["Setting", "Meaning", "Value", "Range"], rows)
        )
    for pid in (s.get("plc_settings") or {}).get("pids") or []:
        points = int(pid.get("points") or 0)
        lo, hi = float(pid.get("min", 0)), float(pid.get("max", 0))
        width = (hi - lo) / points if points else 0
        rows = [
            [
                str(b),
                f"{_g(lo + b * width)} … {_g(lo + (b + 1) * width)} °C",
                _g((pid.get("p") or [None] * points)[b]),
                _g((pid.get("i") or [None] * points)[b]),
                _g((pid.get("d") or [None] * points)[b]),
            ]
            for b in range(points)
        ]
        parts.append(
            f"\n\n## PID table `{pid.get('name')}` ({pid.get('label', '')})\n\n"
            f"{points} bands over {_g(lo)} … {_g(hi)} °C; the band in use is `temp_pid_idx`.\n\n"
            + _table(["Band", "Range", "Kp", "Ki", "Kd"], rows)
        )
    for cal in (s.get("plc_settings") or {}).get("calibrations") or []:
        rows = [
            [_g(x), _g(d)] for x, d in zip(cal.get("x") or [], cal.get("delta") or [], strict=False)
        ]
        parts.append(
            f"\n\n## Calibration `{cal.get('name')}` of `{cal.get('state_name')}`\n\n"
            f"Correction added at each measured temperature (at most {_g(cal.get('delta_max'))} °C).\n\n"
            + _table(["Measured, °C", "Correction, °C"], rows)
        )
    monitor = s.get("monitor") or []
    if monitor:
        parts.append(
            "\n\n## Output bits\n\nBits of `outputs`: which component is on.\n\n"
            + _table(
                ["Bit", "Component"], [[str(m.get("bit")), m.get("label", "")] for m in monitor]
            )
        )
    return "".join(parts) + "\n"


def _rows(conn, sql, args=()):
    return conn.execute(sql, args).fetchall()


def experiment_history(conn: sqlite3.Connection) -> str:
    page = _header(
        "experiment-history",
        "Experiment history",
        ["history", "experiments", "runs", "statistics", "groups", "anomalies"],
        ["experiments database (data/deepvac_brain.sqlite3, built from the run database)"],
        "What the run history holds: how many experiments, when, of which kind, at which setpoints, and "
        "what went wrong. Details of any experiment: the analyst's tools or [[data-and-recordings]].",
    )
    parts = [page]
    total, control, first, last, hours = conn.execute(
        "SELECT COUNT(*), SUM(has_control), MIN(start_time), MAX(start_time), SUM(duration_s) / 3600.0 FROM experiments"
    ).fetchone()
    if not total:
        return page + "\nNo experiments yet.\n"
    parts.append(
        f"\n## Overview\n\n{total} experiments (#1 … #{total}) from {first} to {last}, "
        f"{_g(hours, 4)} hours recorded; {control} have temperature and setpoint (KPIs).\n\n"
    )
    parts.append(
        _table(
            ["Source", "Experiments"],
            [
                [s or "—", str(n)]
                for s, n in _rows(
                    conn, "SELECT source, COUNT(*) FROM experiments GROUP BY source ORDER BY 2 DESC"
                )
            ],
        )
    )
    parts.append(
        "\n\n## By month\n\n"
        + _table(
            ["Month", "Experiments", "Hours"],
            [
                [m, str(n), _g(h, 3)]
                for m, n, h in _rows(
                    conn,
                    "SELECT substr(start_time, 1, 7), COUNT(*), SUM(duration_s) / 3600.0 FROM experiments "
                    "GROUP BY 1 ORDER BY 1",
                )
            ],
        )
    )
    groups = _rows(
        conn,
        "SELECT group_name, COUNT(*), MIN(number), MAX(number), MIN(start_time), MAX(start_time) "
        "FROM experiments GROUP BY group_name ORDER BY 2 DESC LIMIT 20",
    )
    parts.append(
        "\n\n## By series (group)\n\n"
        + _table(
            ["Series", "Experiments", "Numbers", "First", "Last"],
            [[g or "—", str(n), f"#{a} … #{b}", f[:10], z[:10]] for g, n, a, b, f, z in groups],
        )
    )
    by_level = defaultdict(list)
    for sp, tail in _rows(
        conn,
        "SELECT final_setpoint_c, tail_mae FROM experiments WHERE has_control = 1 "
        "AND final_setpoint_c IS NOT NULL",
    ):
        by_level[round(sp)].append(tail)
    rows = []
    for level, tails in sorted(by_level.items(), key=lambda kv: -len(kv[1]))[:15]:
        valid = [t for t in tails if t is not None]
        rows.append(
            [f"{level} °C", str(len(tails)), _g(statistics.median(valid)) if valid else "—"]
        )
    parts.append(
        "\n\n## By final setpoint\n\nExperiments with KPIs, by their last setpoint level.\n\n"
        + _table(["Setpoint", "Experiments", "Median tail MAE, °C"], rows)
    )
    anomalies = _rows(
        conn,
        "SELECT kind, severity, COUNT(*), COUNT(DISTINCT experiment) FROM anomalies "
        "GROUP BY kind, severity ORDER BY 3 DESC",
    )
    if anomalies:
        parts.append(
            "\n\n## Anomalies\n\n"
            + _table(
                ["Kind", "Severity", "Found", "In experiments"],
                [[k, s, str(n), str(e)] for k, s, n, e in anomalies],
            )
        )
    profiles = _rows(
        conn,
        "SELECT test_profile, COUNT(*) FROM experiments WHERE test_profile IS NOT NULL "
        "GROUP BY 1 ORDER BY 2 DESC LIMIT 10",
    )
    if profiles:
        parts.append(
            "\n\n## Test profiles run\n\n"
            + _table(["Profile", "Experiments"], [[p, str(n)] for p, n in profiles])
        )
    days = _rows(
        conn,
        "SELECT chamber, COUNT(*), MIN(day), MAX(day), SUM(mb) FROM recordings GROUP BY chamber",
    )
    if days:
        parts.append(
            "\n\n## Full-day recordings\n\n"
            + _table(
                ["Chamber", "Days", "First", "Last", "MB"],
                [[c, str(n), f, z, _g(mb, 3)] for c, n, f, z, mb in days],
            )
        )
    log = conn.execute(
        "SELECT COUNT(*), MIN(time), MAX(time) FROM events WHERE source = 'control log'"
    ).fetchone()
    if log and log[0]:
        parts.append(
            f"\n\n## Deepvac Control's event log\n\n{log[0]} messages from {log[1]} to {log[2]} "
            "(table `events`, source `control log`)."
        )
    return "".join(parts) + "\n"


def pid_tuning_lessons(conn: sqlite3.Connection, min_runs: int = 5, min_step_c: float = 5.0) -> str:
    page = _header(
        "pid-tuning-lessons",
        "PID tuning: what the experiments show",
        [
            "pid",
            "tuning",
            "lessons",
            "gains",
            "kp",
            "ki",
            "kd",
            "overshoot",
            "settling",
            "step response",
        ],
        [
            "experiments database (data/deepvac_brain.sqlite3, table stages)",
            "KPIs as defined in analysis-kpis",
        ],
        "Step responses grouped by target temperature and direction: how they performed and which PID gains did "
        "best. Facts from the recorded runs, not recommendations: conditions differ between runs (starting "
        "temperature, load, chamber state). Read with [[pid-control]] and [[analysis-kpis]].",
    )
    parts = [page]
    steps = _rows(
        conn,
        f"""
        SELECT s.experiment, s.stage, s.reference_end_c, s.start_temp_c, s.kp, s.ki, s.kd, s.tail_mae, s.overshoot,
               s.settling_time_s, s.cost, s.saturated_fraction, s.duration_s
        FROM stages s
        WHERE s.kind = 'setpoint' AND s.cost IS NOT NULL AND s.kp IS NOT NULL AND s.start_temp_c IS NOT NULL
          AND abs(s.reference_end_c - s.start_temp_c) >= {min_step_c}""",
    )
    groups = defaultdict(list)
    for r in steps:
        direction = "heating" if r[2] > r[3] else "cooling"
        groups[(round(r[2]), direction)].append(r)
    keys = sorted(
        (k for k, rs in groups.items() if len(rs) >= min_runs), key=lambda k: -len(groups[k])
    )[:12]
    if not keys:
        return (
            page + f"\nNo target has {min_runs} step responses of {min_step_c:g} °C or more yet.\n"
        )
    parts.append(
        f"\nStep responses (setpoint stages) of at least {min_step_c:g} °C: {len(steps)}. Targets with "
        f"{min_runs} or more, most first: {', '.join(f'{lv} °C {d}' for lv, d in keys)}. Gains are those in use "
        "during the step; cost = tail MAE + 10 × overshoot + 0.5 × tail std + 0.5 × |final error|.\n"
    )

    def med(values):
        values = [v for v in values if v is not None]
        return statistics.median(values) if values else None

    for level, direction in keys:
        rs = groups[(level, direction)]
        settled = sum(1 for r in rs if r[9] is not None)
        parts.append(
            f"\n## {level} °C, {direction} ({len(rs)} steps, {len({r[0] for r in rs})} experiments)\n\n"
            f"Median tail MAE {_g(med([r[7] for r in rs]))} °C, overshoot {_g(med([r[8] for r in rs]))} °C, "
            f"settling {_g(med([r[9] for r in rs]))} s ({settled} of {len(rs)} settled within ±0.5 °C), output "
            f"saturated {_g((med([r[11] for r in rs]) or 0) * 100, 3)} % of the time.\n\n"
        )
        best = sorted(rs, key=lambda r: r[10])[:5]
        parts.append(
            "Best five by cost:\n\n"
            + _table(
                [
                    "Run (stage)",
                    "From, °C",
                    "Kp",
                    "Ki",
                    "Kd",
                    "Tail MAE, °C",
                    "Overshoot, °C",
                    "Settling, s",
                    "Cost",
                ],
                [
                    [f"#{r[0]} ({r[1]})", r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[10]]
                    for r in best
                ],
            )
        )
        gains = defaultdict(list)
        for r in rs:
            gains[(round(r[4], 3), round(r[5], 3), round(r[6], 3))].append(r)
        repeated = [(g, grs) for g, grs in gains.items() if len(grs) >= 3]
        if repeated:
            ranked = sorted(repeated, key=lambda item: med([r[10] for r in item[1]]))[:5]
            parts.append(
                "\n\nGains used for 3 or more of these steps, by median cost:\n\n"
                + _table(
                    [
                        "Kp",
                        "Ki",
                        "Kd",
                        "Steps",
                        "Median tail MAE, °C",
                        "Median overshoot, °C",
                        "Median cost",
                        "Examples",
                    ],
                    [
                        [
                            g[0],
                            g[1],
                            g[2],
                            str(len(grs)),
                            med([r[7] for r in grs]),
                            med([r[8] for r in grs]),
                            med([r[10] for r in grs]),
                            ", ".join(f"#{r[0]}" for r in sorted(grs, key=lambda r: r[10])[:3]),
                        ]
                        for g, grs in ranked
                    ],
                )
            )
        parts.append("\n")
    return "".join(parts) + "\n"
